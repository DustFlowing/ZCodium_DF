// Rebuild the static, source-defined vocabulary accepted by diagnostic log sinks.
import { readdir, readFile, writeFile } from "node:fs/promises";
import { relative, resolve } from "node:path";
import { pathToFileURL } from "node:url";
import ts from "typescript";
const root = resolve(import.meta.dirname, "..");
const skipped = new Set([
  "node_modules",
  "out",
  "dist",
  "build",
  ".git",
  ".turbo",
  "coverage",
  "test",
  "tests",
  "__tests__",
  "fixtures",
  "examples",
]);
// 修复：Windows 上 resolve() 返回反斜杠路径，原先直接用 path.includes("/src/") 判断，
// 所有文件都被跳过，生成出几乎为空的目录（只剩 4 条内置消息），日志在生产环境被整行写成 [omitted]。
// 统一把分隔符归一化为正斜杠后再做路径判断，保证 Windows 与 POSIX 生成结果一致。
export function toPosixPath(path) {
  return path.replaceAll("\\", "/");
}
export function isCatalogSource(path) {
  const normalized = toPosixPath(path);
  return (
    normalized.includes("/src/") &&
    /\.(ts|tsx|js|mjs)$/.test(normalized) &&
    !/\.test\.|\.spec\.|\.d\.ts$|diagnosticLogCatalog/.test(normalized)
  );
}
const builtinMessages = ["diagnostic", "[omitted]", "[diagnostic]", "[local-diagnostic]"];
const messages = new Set(builtinMessages);
const prefixes = new Set();
const modules = [];
async function walk(dir) {
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    if (skipped.has(entry.name)) continue;
    const path = resolve(dir, entry.name);
    if (entry.isDirectory()) {
      await walk(path);
      continue;
    }
    if (!isCatalogSource(path)) continue;
    modules.push(toPosixPath(relative(root, path)));
    const source = ts.createSourceFile(
      path,
      await readFile(path, "utf8"),
      ts.ScriptTarget.Latest,
      true,
    );
    function visit(node) {
      if (ts.isCallExpression(node)) {
        const callee = node.expression.getText(source);
        if (/(?:logger|log|console|createServiceLogger|createLogger)/i.test(callee)) {
          for (const arg of node.arguments) {
            if (
              ts.isStringLiteralLike(arg) &&
              arg.text.length <= 400 &&
              !/https?:\/\/|[A-Z]:\\/.test(arg.text)
            )
              messages.add(arg.text);
            if (
              ts.isTemplateExpression(arg) &&
              arg.head.text.trim().length >= 8 &&
              !/https?:\/\//.test(arg.head.text)
            )
              prefixes.add(arg.head.text);
          }
        }
      }
      ts.forEachChild(node, visit);
    }
    visit(source);
  }
}
export async function collectDiagnosticLogCatalog() {
  messages.clear();
  for (const builtin of builtinMessages) messages.add(builtin);
  prefixes.clear();
  modules.length = 0;
  await walk(resolve(root, "packages"));
  await walk(resolve(root, "apps/zcode-cli/packages"));
  return {
    messages: [...messages].sort(),
    prefixes: [...prefixes].sort(),
    modules: [...modules].sort(),
  };
}
// 仅作为入口脚本执行时才写文件，测试 import 本模块不产生副作用。
if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  const catalog = await collectDiagnosticLogCatalog();
  const output = `/* eslint-disable max-lines -- Generated static vocabulary, not implementation. */\n// Generated by node scripts/diagnostic-log-catalog.mjs. No runtime/user data.\nexport const diagnosticMessages: readonly string[] = ${JSON.stringify(catalog.messages, null, 2)};\nexport const diagnosticPrefixes: readonly string[] = ${JSON.stringify(catalog.prefixes, null, 2)};\nexport const diagnosticModules: readonly string[] = ${JSON.stringify(catalog.modules, null, 2)};\n`;
  await writeFile(resolve(root, "packages/shared/src/diagnosticLogCatalog.ts"), output);
}
